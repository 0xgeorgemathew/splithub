/**
 * One-off migration of the Supabase Postgres data into D1.
 *
 *   SUPABASE_URL=... SUPABASE_KEY=... bun scripts/migrate-from-supabase.ts > /tmp/splithub-data.sql
 *   wrangler d1 execute splithub --remote --file /tmp/splithub-data.sql
 *
 * Reads every table through PostgREST, converts values with the same rules the D1 engine uses
 * (booleans -> 0/1, JSON/arrays -> TEXT, timestamps -> ISO UTC) and emits INSERTs in foreign-key order.
 */
import { toSqlValue } from "../lib/db/engine";
import { schema } from "../lib/db/schema";

const url = process.env.SUPABASE_URL ?? process.env.NEXT_PUBLIC_SUPABASE_URL;
const key = process.env.SUPABASE_KEY ?? process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
if (!url || !key) throw new Error("Set SUPABASE_URL and SUPABASE_KEY");

function tablesInDependencyOrder() {
  const ordered: string[] = [];
  const visit = (table: string, path: string[] = []) => {
    if (ordered.includes(table)) return;
    if (path.includes(table)) throw new Error(`FK cycle: ${[...path, table].join(" -> ")}`);
    for (const fk of schema[table].foreignKeys) if (fk.refTable !== table) visit(fk.refTable, [...path, table]);
    ordered.push(table);
  };
  Object.keys(schema).forEach(table => visit(table));
  return ordered;
}

function literal(value: unknown): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}

async function fetchRows(table: string): Promise<Record<string, unknown>[]> {
  const rows: Record<string, unknown>[] = [];
  const pageSize = 1000;
  for (let offset = 0; ; offset += pageSize) {
    const response = await fetch(`${url}/rest/v1/${table}?select=*`, {
      headers: { apikey: key!, Authorization: `Bearer ${key}`, Range: `${offset}-${offset + pageSize - 1}` },
    });
    if (!response.ok) throw new Error(`${table}: ${response.status} ${await response.text()}`);
    const page = (await response.json()) as Record<string, unknown>[];
    rows.push(...page);
    if (page.length < pageSize) return rows;
  }
}

const out: string[] = ["-- Generated by scripts/migrate-from-supabase.ts", "PRAGMA defer_foreign_keys = true;"];
const summary: Record<string, number> = {};

for (const table of tablesInDependencyOrder()) {
  const def = schema[table];
  const rows = await fetchRows(table);
  summary[table] = rows.length;
  out.push(`DELETE FROM "${table}";`);
  for (const row of rows) {
    const unknown = Object.keys(row).filter(column => !(column in def.columns));
    if (unknown.length) throw new Error(`${table} has columns missing from the D1 schema: ${unknown.join(", ")}`);
    const columns = Object.keys(def.columns).filter(column => column in row);
    const values = columns.map(column => literal(toSqlValue(def.columns[column], row[column])));
    out.push(`INSERT INTO "${table}" (${columns.map(c => `"${c}"`).join(", ")}) VALUES (${values.join(", ")});`);
  }
}

// Inserting explicit ids advances the AUTOINCREMENT counters, so new rows continue after them.
console.log(out.join("\n"));
console.error("Exported rows:", summary);
